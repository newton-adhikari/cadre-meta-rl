#!/usr/bin/env python3
"""Aggregate completed P2 single-seed results into Figures and tables.

This will be used for paper later
if i decide to release.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from pathlib import Path

import numpy as np

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from meta_rl_tb3.evaluation.metrics import aggregate_seeds, format_summary_row
from experiments.run_p2_adaptation_curves import (
    BUDGET_SCHEDULE,
    plot_adaptation_curves,
)


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--output-dir", type=str, default="results/p2_full")
    p.add_argument("--methods",    nargs="+", default=["cadre", "fomaml", "ppo_ft"])
    p.add_argument("--partial",    action="store_true",
                   help="Do not error on missing seeds")
    p.add_argument("--min-seeds",  type=int, default=3,
                   help="Minimum seeds required to produce a result (default 3)")
    return p.parse_args()


def load_seed_metrics(out_dir: Path, method: str, partial: bool,
                      split: str = None) -> list:
    """Load per-seed metric JSONs for a method, optionally filtered by split.

    Args:
        split: If given, only load files whose 'split' field matches
               (e.g. 'iid', 'ood').  If None, loads everything and
               warns when different splits are mixed.
    """
    if split is not None:
        # New naming convention: metrics_<method>_seed<N>_<split>.json
        files = sorted(out_dir.glob(f"metrics_{method}_seed*_{split}.json"))
        # Also accept legacy files that have no split suffix but correct split field
        legacy = [f for f in out_dir.glob(f"metrics_{method}_seed*.json")
                  if f.stem.count('_') == 3]  # metrics_method_seedN only (no split suffix)
    else:
        files = sorted(out_dir.glob(f"metrics_{method}_seed*.json"))
        legacy = []

    all_files = list(files) + legacy

    if not all_files:
        if not partial:
            raise FileNotFoundError(
                f"No results found for method '{method}' split='{split}' in {out_dir}."
            )
        return []

    records = []
    for f in all_files:
        with open(f) as fh:
            d = json.load(fh)
        d = {k: (math.inf if v == "inf" else v) for k, v in d.items()}
        # Apply split filter on the 'split' field inside the record
        if split is not None and d.get("split", "") != split:
            continue
        records.append(d)

    # Deduplicate by (seed, split) — keep the most recent file if duplicates exist
    seen = {}
    deduped = []
    for r in records:
        key = (r.get("seed"), r.get("split", ""))
        if key not in seen:
            seen[key] = r
            deduped.append(r)
    return deduped


def make_latex_table(
    agg_by_method: dict,
    budget_schedule: list,
    n_seeds_by_method: dict,
    out_path: Path,
) -> None:
    """Write a LaTeX tabular stub for Table 1."""
    # Use 0-shot and max-budget SR plus AUC-SR for the table
    b_zero = budget_schedule[0]
    b_max  = budget_schedule[-1]

    lines = [
        "% Table 1: Adaptation-curve summary — auto-generated by aggregate_p2_results.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\begin{tabular}{l ccc ccc c}",
        r"\toprule",
        r"Method & \multicolumn{3}{c}{SR@0 (zero-shot)} & "
        r"\multicolumn{3}{c}{SR@" + str(b_max) + r" (max budget)} & AUC-SR \\",
        r"& mean & SD & N & mean & SD & N & mean \\",
        r"\midrule",
    ]

    label_map = {"cadre": "CADRE (ours)", "fomaml": "FOMAML", "ppo_ft": "PPO-FT"}

    for method in agg_by_method:
        agg   = agg_by_method[method]
        label = label_map.get(method, method)
        n     = n_seeds_by_method.get(method, "?")

        def _fmt(key, stat):
            v = agg.get(key, {}).get(stat, float("nan"))
            if math.isnan(v): return "--"
            return f"{v:.3f}"

        sr0_mean = _fmt(f"sr_at_{b_zero}", "mean")
        sr0_std  = _fmt(f"sr_at_{b_zero}", "std")
        srN_mean = _fmt(f"sr_at_{b_max}",  "mean")
        srN_std  = _fmt(f"sr_at_{b_max}",  "std")
        auc_mean = _fmt("auc_sr",           "mean")

        lines.append(
            rf"{label} & {sr0_mean} & {sr0_std} & {n} & "
            rf"{srN_mean} & {srN_std} & {n} & {auc_mean} \\"
        )

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{P2 adaptation-curve results (goal-reaching with train-split"
        r" dynamics perturbations). SR = success rate. AUC-SR = area under"
        r" SR vs log10(budget+1) curve. N = number of independent seeds.}",
        r"\label{tab:p2_results}",
        r"\end{table}",
    ]

    out_path.write_text("\n".join(lines) + "\n")
    print(f"  LaTeX table → {out_path}")


def main():
    args = parse_args()
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    SPLITS = ["iid", "ood"]  # report each split separately

    print(f"{'='*60}")
    print(f"P2 Result Aggregation")
    print(f"  Source:  {out_dir}")
    print(f"  Methods: {args.methods}")
    print(f"  Splits:  {SPLITS}")
    print(f"{'='*60}")

    for split in SPLITS:
        print(f"\n{'─'*60}")
        print(f"  SPLIT: {split.upper()}")
        print(f"{'─'*60}")

        agg_by_method      = {}
        n_seeds_by_method  = {}

        for method in args.methods:
            records = load_seed_metrics(out_dir, method, args.partial, split=split)
            if not records:
                print(f"  {method}: no {split} results found — skipping")
                continue
            if len(records) < args.min_seeds and not args.partial:
                print(f"  WARNING: {method} has only {len(records)} seeds "
                      f"(minimum: {args.min_seeds})")

            n_seeds_by_method[method] = len(records)
            agg = aggregate_seeds(records)
            agg_by_method[method] = agg

            # Console summary
            show = [b for b in BUDGET_SCHEDULE[::max(1, len(BUDGET_SCHEDULE)//4)]]
            print(f"\n  {method.upper()}  (n={len(records)} seeds, split={split})")
            print("  " + format_summary_row(method, agg, show))
            for b in BUDGET_SCHEDULE:
                key = f"sr_at_{b}"
                if key in agg:
                    a = agg[key]
                    n_adapt = b // max(1, 200)
                    print(f"    budget={b:5d} ({n_adapt:2d} eps) "
                          f"SR={a['mean']:.3f} ± {a['std']:.3f}  (n={a['n_seeds']})")
            if "auc_sr" in agg:
                print(f"    AUC-SR = {agg['auc_sr']['mean']:.4f} ± {agg['auc_sr']['std']:.4f}")
            if "k_threshold" in agg:
                k_val = agg["k_threshold"]["mean"]
                print(f"    K_70   = {'inf' if math.isinf(k_val) else int(k_val)}")

        if not agg_by_method:
            print(f"  No results for split={split}")
            continue

        # Write per-split aggregated JSON
        agg_path = out_dir / f"aggregated_metrics_{split}.json"
        def _safe(obj):
            if isinstance(obj, float) and math.isinf(obj): return "inf"
            return obj
        with open(agg_path, "w") as f:
            json.dump(
                {m: {k: {sk: _safe(sv) for sk, sv in v.items()} for k, v in agg.items()}
                 for m, agg in agg_by_method.items()},
                f, indent=2,
            )
        print(f"\n  Aggregated JSON ({split}) → {agg_path}")

        # Write per-split CSV
        all_keys = sorted({k for agg in agg_by_method.values() for k in agg})
        csv_path = out_dir / f"summary_{split}.csv"
        with open(csv_path, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["method", "n_seeds"]
                       + [f"{k}_mean" for k in all_keys]
                       + [f"{k}_std"  for k in all_keys])
            for method, agg in agg_by_method.items():
                row = [method, n_seeds_by_method.get(method, 0)]
                row += [agg.get(k, {}).get("mean", float("nan")) for k in all_keys]
                row += [agg.get(k, {}).get("std",  float("nan")) for k in all_keys]
                w.writerow(row)
        print(f"  Summary CSV ({split}) → {csv_path}")

        # Figure per split
        fig_path = out_dir / f"fig4_adaptation_curves_{split}.pdf"
        n_s = list(n_seeds_by_method.values())
        plot_adaptation_curves(
            agg_by_method, BUDGET_SCHEDULE, save_path=fig_path,
            title=f"P2 Adaptation Curves — {split.upper()} dynamics (n={n_s})",
        )

        # LaTeX table per split
        tex_path = out_dir / f"table1_{split}.tex"
        make_latex_table(agg_by_method, BUDGET_SCHEDULE, n_seeds_by_method, tex_path)

        # Kill-criteria check (OOD is the primary claim)
        if split == "ood":
            print(f"\n  Kill-criteria check ({split.upper()}):")
            cadre_auc  = agg_by_method.get("cadre",  {}).get("auc_sr", {}).get("mean", float("nan"))
            fomaml_auc = agg_by_method.get("fomaml", {}).get("auc_sr", {}).get("mean", float("nan"))
            ppo_auc    = agg_by_method.get("ppo_ft", {}).get("auc_sr", {}).get("mean", float("nan"))
            def _check(label, a, b):
                if math.isnan(a) or math.isnan(b):
                    print(f"    [PENDING] {label}")
                elif a > b:
                    print(f"    [PASS]    {label}  (delta={a-b:+.4f})")
                else:
                    print(f"    [FAIL]    {label}  (delta={a-b:+.4f}) — reassess hypothesis")
            _check("K1: CADRE OOD AUC-SR > FOMAML OOD AUC-SR", cadre_auc, fomaml_auc)
            _check("K2: CADRE OOD AUC-SR > PPO-FT OOD AUC-SR", cadre_auc, ppo_auc)
            if not math.isnan(cadre_auc) and not math.isnan(fomaml_auc):
                cadre_gain  = agg_by_method.get("cadre",  {}).get("adaptation_gain", {}).get("mean", float("nan"))
                fomaml_gain = agg_by_method.get("fomaml", {}).get("adaptation_gain", {}).get("mean", float("nan"))
                print(f"    Mean adaptation gain:  CADRE={cadre_gain:+.3f}  FOMAML={fomaml_gain:+.3f}")

    print(f"\nAggregation complete → {out_dir.resolve()}")


if __name__ == "__main__":
    main()
